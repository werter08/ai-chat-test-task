// Usage: swift scripts/obfuscate_key.swift <env-file> <output-swift-file>
//
// Reads OPENROUTER_API_KEY (and optional OPENROUTER_MODEL) from the .env file and writes
// Shared/Security/Secrets.generated.swift with the key XOR-ed with a random salt, so the key is not
// present as a plain string in the repo or the binary.
//
// NOTE: this is obfuscation, not encryption. Anyone with the binary can recover the key.
// If the .env has no real key, the existing output file is left untouched (exit code 0).
import Foundation

let args = CommandLine.arguments
guard args.count == 3 else {
    FileHandle.standardError.write(Data("usage: obfuscate_key.swift <env> <out>\n".utf8))
    exit(2)
}
let envPath = args[1]
let outPath = args[2]

func parseEnv(_ text: String) -> [String: String] {
    var result: [String: String] = [:]
    for rawLine in text.split(whereSeparator: \.isNewline) {
        let line = rawLine.trimmingCharacters(in: .whitespaces)
        if line.isEmpty || line.hasPrefix("#") { continue }
        guard let eq = line.firstIndex(of: "=") else { continue }
        let name = line[..<eq].trimmingCharacters(in: .whitespaces)
        var value = line[line.index(after: eq)...].trimmingCharacters(in: .whitespaces)
        if value.count >= 2, let f = value.first, let l = value.last, f == l, f == "\"" || f == "'" {
            value = String(value.dropFirst().dropLast())
        }
        result[name] = value
    }
    return result
}

guard let envText = try? String(contentsOfFile: envPath, encoding: .utf8) else {
    print("obfuscate_key: \(envPath) not found — keeping existing Secrets.generated.swift")
    exit(0)
}
let env = parseEnv(envText)
let key = env["OPENROUTER_API_KEY"] ?? ""
let model = (env["OPENROUTER_MODEL"] ?? "").isEmpty ? "baidu/ernie-5.5-flash-preview:free" : env["OPENROUTER_MODEL"]!

let visionModel = (env["OPENROUTER_VISION_MODEL"] ?? "").isEmpty ? "nvidia/nemotron-3.5-super-vl" : env["OPENROUTER_VISION_MODEL"]!

let isPlaceholder = key.isEmpty || key.contains("<") || key.uppercased().contains("API_KEY") || key.uppercased().contains("PASTE")
if isPlaceholder {
    print("obfuscate_key: no real OPENROUTER_API_KEY in .env — keeping existing Secrets.generated.swift")
    exit(0)
}

var salt = [UInt8](repeating: 0, count: 32)
for i in salt.indices { salt[i] = UInt8.random(in: 0...255) }
let blob = key.utf8.enumerated().map { $0.element ^ salt[$0.offset % salt.count] }

func literal(_ bytes: [UInt8]) -> String {
    stride(from: 0, to: bytes.count, by: 16)
        .map { start in
            "        " + bytes[start..<min(start + 16, bytes.count)].map { String(format: "0x%02X", $0) }.joined(separator: ", ") + ","
        }
        .joined(separator: "\n")
}

let output = """
// GENERATED by scripts/obfuscate_key.swift — do not edit by hand.
// The key is XOR-obfuscated (not encrypted). See KeyVault.swift.

enum Secrets {
    static let blob: [UInt8] = [
\(literal(blob))
    ]

    static let salt: [UInt8] = [
\(literal(salt))
    ]

    static let model = "\(model)"

    /// Used for requests that contain a photo.
    static let visionModel = "\(visionModel)"
}

"""
do {
    try output.write(toFile: outPath, atomically: true, encoding: .utf8)
    print("obfuscate_key: wrote \(outPath) (\(blob.count) bytes obfuscated, model \(model))")
} catch {
    FileHandle.standardError.write(Data("obfuscate_key: cannot write \(outPath): \(error)\n".utf8))
    exit(1)
}
